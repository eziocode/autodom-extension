#!/usr/bin/env node
// Registers (or removes) the AutoDOM native-messaging helper,
// "com.autodom.bridge", for every installed Chromium browser.
//
// The helper (server/native-host.js) is what lets the extension's Bridge
// check / Fix kill stale AutoDOM servers and start a fresh one without a
// terminal. Shared by setup.sh and setup.ps1 so both installers register it
// identically.
//
// Usage:
//   node scripts/native-host-install.mjs [--server-dir DIR]
//        [--extension-id ID]... [--uninstall] [--json]
//
// Writes, per user (no admin needed):
//   • a launcher wrapper with the absolute node path baked in — Chrome
//     starts native hosts with a minimal PATH that lacks nvm/brew node;
//   • the host manifest into each browser's NativeMessagingHosts dir
//     (macOS/Linux), or registers it under HKCU (Windows).

import { execFileSync } from "node:child_process";
import {
  accessSync,
  chmodSync,
  constants,
  existsSync,
  mkdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { homedir } from "node:os";
import { delimiter, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HOST_NAME = "com.autodom.bridge";
const DEFAULT_EXTENSION_ID = "kpjdffgogiajnkajnjneiboaincnaokf";
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

function parseArgs(argv) {
  const opts = {
    serverDir: join(ROOT, "server"),
    extensionIds: [],
    uninstall: false,
    json: false,
  };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--server-dir") opts.serverDir = resolve(argv[++i]);
    else if (a === "--extension-id") opts.extensionIds.push(argv[++i]);
    else if (a === "--uninstall") opts.uninstall = true;
    else if (a === "--json") opts.json = true;
    else throw new Error(`Unknown argument: ${a}`);
  }
  return opts;
}

// Browser user-data roots whose presence means "this browser is installed".
function posixBrowserDirs() {
  const home = homedir();
  if (process.platform === "darwin") {
    const base = join(home, "Library", "Application Support");
    return [
      "Google/Chrome",
      "Google/Chrome Beta",
      "Google/Chrome Dev",
      "Google/Chrome Canary",
      "Chromium",
      "BraveSoftware/Brave-Browser",
      "Microsoft Edge",
      "Microsoft Edge Beta",
      "Microsoft Edge Dev",
      "Microsoft Edge Canary",
      "Arc/User Data",
      "Vivaldi",
      "Zoho/Ulaa",
    ].map((d) => join(base, d));
  }
  const cfg = process.env.XDG_CONFIG_HOME || join(home, ".config");
  return [
    "google-chrome",
    "google-chrome-beta",
    "google-chrome-unstable",
    "chromium",
    "BraveSoftware/Brave-Browser",
    "microsoft-edge",
    "microsoft-edge-beta",
    "microsoft-edge-dev",
    "vivaldi",
  ].map((d) => join(cfg, d));
}

const WINDOWS_REGISTRY_ROOTS = [
  "HKCU\\Software\\Google\\Chrome",
  "HKCU\\Software\\Chromium",
  "HKCU\\Software\\BraveSoftware\\Brave-Browser",
  "HKCU\\Software\\Microsoft\\Edge",
  "HKCU\\Software\\Vivaldi",
  "HKCU\\Software\\Zoho\\Ulaa",
];

function hostHome() {
  if (process.platform === "win32") {
    return join(
      process.env.LOCALAPPDATA || join(homedir(), "AppData", "Local"),
      "AutoDOM",
      "native-host",
    );
  }
  if (process.platform === "darwin") {
    return join(homedir(), "Library", "Application Support", "AutoDOM", "native-host");
  }
  return join(
    process.env.XDG_CONFIG_HOME || join(homedir(), ".config"),
    "autodom",
    "native-host",
  );
}

// Prefer the `node` found on PATH (e.g. /opt/homebrew/bin/node, a stable
// symlink) over process.execPath, which resolves to a version-pinned Cellar
// path that disappears on the next `brew upgrade`.
function stableNodePath() {
  const exe = process.platform === "win32" ? "node.exe" : "node";
  for (const dir of (process.env.PATH || "").split(delimiter)) {
    if (!dir) continue;
    const candidate = join(dir, exe);
    try {
      accessSync(candidate, constants.X_OK);
      return candidate;
    } catch {}
  }
  return process.execPath;
}

function writeWrapper(dir, serverDir) {
  const hostJs = join(serverDir, "native-host.js");
  if (!existsSync(hostJs)) throw new Error(`native-host.js not found in ${serverDir}`);
  mkdirSync(dir, { recursive: true });
  if (process.platform === "win32") {
    const path = join(dir, "native-host.bat");
    writeFileSync(
      path,
      `@echo off\r\n"${stableNodePath()}" "${hostJs}" %*\r\n`,
    );
    return path;
  }
  const path = join(dir, "native-host.sh");
  const q = (s) => `'${s.replace(/'/g, `'\\''`)}'`;
  writeFileSync(
    path,
    `#!/bin/sh\n# Generated by AutoDOM setup — re-run setup to refresh.\nexec ${q(stableNodePath())} ${q(hostJs)} "$@"\n`,
  );
  chmodSync(path, 0o755);
  return path;
}

function manifestJson(wrapperPath, extensionIds) {
  return JSON.stringify(
    {
      name: HOST_NAME,
      description: "AutoDOM bridge helper — inspect, flush and restart local AutoDOM servers",
      path: wrapperPath,
      type: "stdio",
      allowed_origins: extensionIds.map((id) => `chrome-extension://${id}/`),
    },
    null,
    2,
  ) + "\n";
}

function install(opts) {
  const ids = [...new Set([DEFAULT_EXTENSION_ID, ...opts.extensionIds])];
  for (const id of ids) {
    if (!/^[a-p]{32}$/.test(id)) throw new Error(`Invalid extension ID '${id}'`);
  }
  const home = hostHome();
  const wrapper = writeWrapper(home, opts.serverDir);
  const manifest = manifestJson(wrapper, ids);
  const registered = [];

  if (process.platform === "win32") {
    const manifestPath = join(home, `${HOST_NAME}.json`);
    writeFileSync(manifestPath, manifest);
    for (const root of WINDOWS_REGISTRY_ROOTS) {
      const key = `${root}\\NativeMessagingHosts\\${HOST_NAME}`;
      try {
        execFileSync("reg", ["add", key, "/ve", "/t", "REG_SZ", "/d", manifestPath, "/f"], {
          stdio: "ignore",
        });
        registered.push(key);
      } catch {}
    }
  } else {
    for (const browserDir of posixBrowserDirs()) {
      if (!existsSync(browserDir)) continue;
      const dir = join(browserDir, "NativeMessagingHosts");
      mkdirSync(dir, { recursive: true });
      const path = join(dir, `${HOST_NAME}.json`);
      writeFileSync(path, manifest);
      registered.push(path);
    }
  }
  return { wrapper, extensionIds: ids, registered };
}

function uninstall() {
  const removed = [];
  if (process.platform === "win32") {
    for (const root of WINDOWS_REGISTRY_ROOTS) {
      const key = `${root}\\NativeMessagingHosts\\${HOST_NAME}`;
      try {
        execFileSync("reg", ["delete", key, "/f"], { stdio: "ignore" });
        removed.push(key);
      } catch {}
    }
  } else {
    for (const browserDir of posixBrowserDirs()) {
      const path = join(browserDir, "NativeMessagingHosts", `${HOST_NAME}.json`);
      if (existsSync(path)) {
        rmSync(path, { force: true });
        removed.push(path);
      }
    }
  }
  rmSync(hostHome(), { recursive: true, force: true });
  return { removed };
}

try {
  const opts = parseArgs(process.argv.slice(2));
  const result = opts.uninstall ? uninstall() : install(opts);
  if (opts.json) {
    process.stdout.write(JSON.stringify(result, null, 2) + "\n");
  } else if (opts.uninstall) {
    console.log(`Removed ${result.removed.length} native-host registration(s).`);
  } else {
    console.log(`Registered ${HOST_NAME} for ${result.registered.length} browser(s).`);
    for (const r of result.registered) console.log(`  ${r}`);
  }
  if (!opts.uninstall && result.registered.length === 0) process.exitCode = 2;
} catch (err) {
  console.error(err?.message || String(err));
  process.exit(1);
}
